-- 1. Unique Index untuk Menjamin Idempotensi Mutlak (Anti-Tagihan Ganda)
-- Mencegah seorang warga menerima 2 tagihan dengan periode dan scope yang sama
create unique index if not exists idx_wargaku_tagihan_unique_periode 
on wargaku_tagihan (
  (data->>'wargaId'), 
  ((data->>'bulan')::int), 
  ((data->>'tahun')::int), 
  (coalesce(data->>'payment_scope', 'RT'))
)
where (data->>'eventId') is null; -- Hanya berlaku untuk tagihan IPL reguler, tagihan kegiatan tetap terpisah

-- 2. Index untuk Mempercepat Pencarian Status dan Tanggal Terbit
create index if not exists idx_wargaku_tagihan_is_auto on wargaku_tagihan (((data->>'isAutoGenerated')::boolean));
create index if not exists idx_wargaku_tagihan_jatuh_tempo on wargaku_tagihan ((data->>'tanggalJatuhTempo'));

-- 3. Fungsi PL/pgSQL untuk Mengecek dan Menerbitkan Tagihan Otomatis
create or replace function fn_check_and_run_auto_billing()
returns jsonb
language plpgsql
security definer
as $$
declare
  v_cfg_row record;
  v_cfg jsonb;
  v_auto_cfg jsonb;
  v_enabled boolean;
  v_publish_day int;
  v_due_day int;
  v_scope text;
  v_now_jkt timestamp with time zone;
  v_cur_year int;
  v_cur_month int;
  v_cur_day int;
  v_max_days int;
  v_effective_publish_day int;
  v_effective_due_day int;
  v_due_date_str text;
  v_period_str text;
  v_warga_rec record;
  v_warga jsonb;
  v_unique_code text;
  v_unique_num int;
  v_nominal_rt numeric := 120000;
  v_nominal_rw numeric := 40000;
  v_total_created int := 0;
  v_total_skipped int := 0;
  v_inv_id text;
  v_inv_obj jsonb;
  v_notif_obj jsonb;
  v_target_owner text;
  v_target_label text;
begin
  -- Waktu sekarang di zona waktu Asia/Jakarta
  v_now_jkt := timezone('Asia/Jakarta', now());
  v_cur_year := extract(year from v_now_jkt)::int;
  v_cur_month := extract(month from v_now_jkt)::int;
  v_cur_day := extract(day from v_now_jkt)::int;

  -- Hitung jumlah hari dalam bulan ini (handle 28/29 Feb, 30 hari, 31 hari)
  v_max_days := extract(day from (date_trunc('month', v_now_jkt) + interval '1 month - 1 day'))::int;

  -- 1. Baca konfigurasi lingkungan
  select * into v_cfg_row from wargaku_config limit 1;
  if not found then
    return jsonb_build_object('success', false, 'message', 'Tabel wargaku_config kosong.');
  end if;

  v_cfg := v_cfg_row.data;
  v_auto_cfg := coalesce(v_cfg->'autoBilling', '{}'::jsonb);

  v_enabled := coalesce((v_auto_cfg->>'enabled')::boolean, true);
  v_publish_day := coalesce((v_auto_cfg->>'publishDay')::int, 5);
  v_due_day := coalesce((v_auto_cfg->>'dueDay')::int, 20);
  v_scope := coalesce(v_auto_cfg->>'scope', 'ALL');

  if not v_enabled then
    return jsonb_build_object('success', true, 'skipped', true, 'message', 'Otomatisasi tagihan nonaktif.');
  end if;

  -- Aturan tanggal akhir bulan
  v_effective_publish_day := least(v_publish_day, v_max_days);
  v_effective_due_day := least(v_due_day, v_max_days);

  -- Belum mencapai tanggal terbit
  if v_cur_day < v_effective_publish_day then
    return jsonb_build_object(
      'success', true, 
      'skipped', true, 
      'message', format('Belum mencapai tanggal terbit (%s/%s/%s). Hari ini tanggal %s.', v_effective_publish_day, v_cur_month, v_cur_year, v_cur_day)
    );
  end if;

  v_due_date_str := to_char(make_date(v_cur_year, v_cur_month, v_effective_due_day), 'YYYY-MM-DD');
  v_period_str := to_char(make_date(v_cur_year, v_cur_month, 1), 'YYYY-MM');

  -- 2. Loop seluruh warga yang aktif
  for v_warga_rec in select * from wargaku_warga where coalesce((data->>'aktif')::boolean, true) = true loop
    v_warga := v_warga_rec.data;
    v_unique_code := coalesce(v_warga->>'kodeUnik', 'WR100');
    v_unique_num := coalesce(substring(v_unique_code from '\d{3}$')::int, 0);

    -- Scope RT
    if v_scope in ('ALL', 'RT') then
      v_inv_id := format('tag-%s-%s-rt-%s', v_cur_year, lpad(v_cur_month::text, 2, '0'), v_warga->>'id');
      
      -- Cek apakah sudah ada (Idempotensi)
      if not exists (select 1 from wargaku_tagihan where id = v_inv_id) then
        v_inv_obj := jsonb_build_object(
          'id', v_inv_id,
          'wargaId', v_warga->>'id',
          'rt_id', coalesce(v_warga->>'rt_id', 'rt-01-01'),
          'namaWarga', v_warga->>'nama',
          'blok', v_warga->>'blok',
          'noRumah', v_warga->>'noRumah',
          'kodeUnik', v_unique_code,
          'bulan', v_cur_month,
          'tahun', v_cur_year,
          'total', v_nominal_rt + v_unique_num,
          'payment_scope', 'RT',
          'pembayaran_kepada', 'Kas Lingkungan RT 01',
          'target_payment_owner', coalesce(v_warga->>'rt_id', 'rt-01-01'),
          'status', 'Belum Bayar',
          'tanggalJatuhTempo', v_due_date_str,
          'tanggalTerbit', to_char(make_date(v_cur_year, v_cur_month, v_effective_publish_day), 'YYYY-MM-DD'),
          'catatan', format('Tagihan Otomatis Bulanan Periode %s', v_period_str),
          'isAutoGenerated', true,
          'submissions', '[]'::jsonb
        );

        insert into wargaku_tagihan (id, data, updated_at)
        values (v_inv_id, v_inv_obj, now())
        on conflict (id) do nothing;

        -- Tambah notifikasi
        v_notif_obj := jsonb_build_object(
          'id', format('notif-db-%s', v_inv_id),
          'userId', v_warga->>'id',
          'residentId', v_warga->>'id',
          'title', format('Tagihan IPL RT Periode %s 📬', v_period_str),
          'message', format('Tagihan IPL Anda sebesar Rp %s telah terbit. Batas jatuh tempo %s.', (v_nominal_rt + v_unique_num), v_due_date_str),
          'type', 'tagihan',
          'targetId', v_inv_id,
          'read', false,
          'created_at', now()
        );

        insert into wargaku_notifications (id, data, updated_at)
        values (v_notif_obj->>'id', v_notif_obj, now())
        on conflict (id) do nothing;

        v_total_created := v_total_created + 1;
      else
        v_total_skipped := v_total_skipped + 1;
      end if;
    end if;

    -- Scope RW
    if v_scope in ('ALL', 'RW') then
      v_inv_id := format('tag-%s-%s-rw-%s', v_cur_year, lpad(v_cur_month::text, 2, '0'), v_warga->>'id');
      
      if not exists (select 1 from wargaku_tagihan where id = v_inv_id) then
        v_inv_obj := jsonb_build_object(
          'id', v_inv_id,
          'wargaId', v_warga->>'id',
          'rt_id', coalesce(v_warga->>'rt_id', 'rt-01-01'),
          'namaWarga', v_warga->>'nama',
          'blok', v_warga->>'blok',
          'noRumah', v_warga->>'noRumah',
          'kodeUnik', v_unique_code,
          'bulan', v_cur_month,
          'tahun', v_cur_year,
          'total', v_nominal_rw + v_unique_num,
          'payment_scope', 'RW',
          'pembayaran_kepada', 'Kas RW 01',
          'target_payment_owner', coalesce(v_warga->>'rw_id', 'rw-01'),
          'status', 'Belum Bayar',
          'tanggalJatuhTempo', v_due_date_str,
          'tanggalTerbit', to_char(make_date(v_cur_year, v_cur_month, v_effective_publish_day), 'YYYY-MM-DD'),
          'catatan', format('Tagihan Otomatis Bulanan Periode %s', v_period_str),
          'isAutoGenerated', true,
          'submissions', '[]'::jsonb
        );

        insert into wargaku_tagihan (id, data, updated_at)
        values (v_inv_id, v_inv_obj, now())
        on conflict (id) do nothing;

        v_total_created := v_total_created + 1;
      else
        v_total_skipped := v_total_skipped + 1;
      end if;
    end if;
  end loop;

  -- 3. Update status monitoring pada wargaku_config
  v_auto_cfg := v_auto_cfg || jsonb_build_object(
    'last_run_at', timezone('Asia/Jakarta', now())::text,
    'last_run_period', v_period_str,
    'last_run_status', 'success',
    'last_run_created_count', v_total_created,
    'last_run_skipped_count', v_total_skipped,
    'last_run_message', format('Eksekusi otomatis selesai. %s tagihan baru dibuat, %s tagihan sudah ada (dilewati).', v_total_created, v_total_skipped),
    'scheduler_heartbeat', timezone('Asia/Jakarta', now())::text
  );

  update wargaku_config
  set data = jsonb_set(data, '{autoBilling}', v_auto_cfg),
      updated_at = now()
  where id = v_cfg_row.id;

  return jsonb_build_object(
    'success', true,
    'totalCreated', v_total_created,
    'totalSkipped', v_total_skipped,
    'period', v_period_str,
    'dueDate', v_due_date_str
  );
end;
$$;

-- 4. Aktifkan Penjadwalan pg_cron di Supabase (Jika ekstensi pg_cron diaktifkan)
-- Menjalankan fn_check_and_run_auto_billing() setiap hari jam 00:05 WIB (17:05 UTC)
do $$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    -- Hapus cron job lama jika sudah ada
    perform cron.unschedule('ipl-auto-billing-daily');
    -- Jadwalkan cron job harian pada 17:05 UTC (00:05 WIB)
    perform cron.schedule('ipl-auto-billing-daily', '5 17 * * *', 'select fn_check_and_run_auto_billing();');
  end if;
exception when others then
  null; -- Abaikan jika pg_cron belum diinstall di tier free
end $$;
